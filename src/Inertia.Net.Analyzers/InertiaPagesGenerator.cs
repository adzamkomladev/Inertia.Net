using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Inertia.Net.Analyzers;

/// <summary>
/// Emits <c>options.TypeScript.AddGeneratedPages()</c>: one <c>Page&lt;TPage&gt;()</c> call per <c>IInertiaPage</c> type declared in the
/// project, found at compile time, so the declarations need no assembly scan (trimming and Native AOT safe).
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class InertiaPagesGenerator : IIncrementalGenerator
{
    internal const string PageInterface = "Inertia.Net.IInertiaPage";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var pages = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is TypeDeclarationSyntax { BaseList: not null } and not InterfaceDeclarationSyntax,
                static (syntax, ct) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, ct) is INamedTypeSymbol type && IsPage(type)
                    ? type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                    : null)
            .Where(static name => name is not null)
            .Collect();
        var available = context.CompilationProvider.Select(static (compilation, _) => compilation.GetTypeByMetadataName(PageInterface) is not null);

        context.RegisterSourceOutput(pages.Combine(available), static (output, input) =>
        {
            if (!input.Right)
            {
                return; // the project does not reference Inertia.Net
            }

            output.AddSource("InertiaGeneratedPages.g.cs", Source(input.Left!));
        });
    }

    internal static bool IsPage(INamedTypeSymbol type) =>
        !type.IsAbstract
        && !type.IsGenericType
        && IsReachable(type)
        && type.AllInterfaces.Any(i => i.ToDisplayString() == PageInterface);

    // The generated class is internal to the project: private or protected nested types cannot be named from it.
    private static bool IsReachable(INamedTypeSymbol type) =>
        type.DeclaredAccessibility is not (Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal)
        && (type.ContainingType is not { } outer || IsReachable(outer));

    private static string Source(ImmutableArray<string?> pages)
    {
        var text = new StringBuilder();
        text.Append("""
            // <auto-generated/>
            #nullable enable

            namespace Inertia.Net
            {
                /// <summary>The <see cref="global::Inertia.Net.IInertiaPage"/> types of this project, found at compile time.</summary>
                internal static class InertiaGeneratedPages
                {
                    /// <summary>
                    /// Declares every <see cref="global::Inertia.Net.IInertiaPage"/> type of this project, as <c>Page&lt;TPage&gt;()</c> does for one.
                    /// Unlike <c>PagesFrom(assembly)</c> it uses no reflection, so it is safe under trimming and Native AOT.
                    /// </summary>
                    public static global::Inertia.Net.InertiaTypeScriptOptions AddGeneratedPages(this global::Inertia.Net.InertiaTypeScriptOptions options)
                    {

            """);
        foreach (var page in pages.Distinct().OrderBy(p => p, System.StringComparer.Ordinal))
        {
            text.Append("            options.Page<").Append(page).Append(">();\n");
        }

        text.Append("""
                        return options;
                    }
                }
            }

            """);
        return text.ToString().Replace("\r\n", "\n");
    }
}
